CREATE TABLE PROSEGUR_TRANSACTIONS_QUEUE
(
  ID_QUEUE        NUMBER                          NOT NULL,
  VTA_IDTRX       NUMBER                          NOT NULL,
  ID_PROSEGUR     NUMBER,
  ESTADO          VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_CREACION  TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  FECHA_PROCESO   TIMESTAMP(6),
  INTENTOS        NUMBER       DEFAULT 0          NOT NULL,
  ERROR_MESSAGE   VARCHAR2(4000),
  CONSTRAINT CK_PROS_TRIG_EST CHECK (ESTADO IN ('PENDIENTE','PROCESANDO','PROCESADO','ERROR')),
  CONSTRAINT PK_PROS_TRIG_QUEUE PRIMARY KEY (ID_QUEUE)
);

CREATE INDEX IDX_PROS_TRANS_QUEUE_ID_PROS   ON PROSEGUR_TRANSACTIONS_QUEUE (ID_PROSEGUR);
CREATE INDEX IDX_PROS_TRANS_QUEUE_VTA_IDTRX ON PROSEGUR_TRANSACTIONS_QUEUE (VTA_IDTRX);
CREATE INDEX IDX_PROS_TRANS_QUEUE_ESTADO    ON PROSEGUR_TRANSACTIONS_QUEUE (ESTADO, ID_QUEUE);

CREATE SEQUENCE SEQ_PROS_TRANS_QUEUE MINVALUE 1 INCREMENT BY 1 START WITH 1 NOCACHE NOORDER NOCYCLE;
